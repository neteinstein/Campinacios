def cabeca(cx, cy, r=45, seed=1, cabelo='curto', boca='sorriso'):
    """Cabeça de boneco: cabelo cheio, olhos, boca e bochechas pintalgadas."""
    s = C(cx, cy, r, 6)
    if cabelo == 'curto':
        s += P(f'M{cx - r} {cy - 5} Q{cx - r * .6} {cy - r * 1.4} {cx + r * .2} {cy - r * 1.05} '
               f'Q{cx + r * 1.1} {cy - r * .9} {cx + r} {cy - 5} Q{cx} {cy - r * .7} {cx - r} {cy - 5} Z', 5, '#000')
    elif cabelo == 'carrapito':
        s += P(f'M{cx - r} {cy - 5} Q{cx} {cy - r * 1.5} {cx + r} {cy - 5} Q{cx} {cy - r * .6} {cx - r} {cy - 5} Z', 5, '#000')
        s += C(cx, cy - r * 1.2, r * .38, 5, '#000')
    elif cabelo == 'comprido':
        s += P(f'M{cx - r * 1.05} {cy + r * 1.3} Q{cx - r * 1.3} {cy - r * 1.4} {cx} {cy - r * 1.1} '
               f'Q{cx + r * 1.3} {cy - r * 1.4} {cx + r * 1.05} {cy + r * 1.3} Q{cx + r * .9} {cy} {cx + r * .6} {cy - r * .5} '
               f'Q{cx} {cy - r * .3} {cx - r * .6} {cy - r * .5} Q{cx - r * .9} {cy} {cx - r * 1.05} {cy + r * 1.3} Z', 5, '#000')
    s += C(cx - r * .35, cy, 5, 0, '#000') + C(cx + r * .35, cy, 5, 0, '#000')
    if boca == 'sorriso':
        s += P(f'M{cx - r * .35} {cy + r * .4} Q{cx} {cy + r * .75} {cx + r * .35} {cy + r * .4}', 5)
    elif boca == 'aberta':
        s += P(f'M{cx - r * .3} {cy + r * .35} Q{cx} {cy + r * .9} {cx + r * .3} {cy + r * .35} Z', 5, '#000')
    s += bochecha(round(cx - r * .62), round(cy + r * .3), 10, seed) + bochecha(round(cx + r * .62), round(cy + r * .3), 10, seed + 1)
    return s


