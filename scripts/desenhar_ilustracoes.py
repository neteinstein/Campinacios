def P(d, w=6, fill='none', extra=''):
    return f'<path d="{d}" stroke-width="{w}" fill="{fill}" {extra}/>'


def C(cx, cy, r, w=6, fill='none'):
    return f'<circle cx="{cx}" cy="{cy}" r="{r}" stroke-width="{w}" fill="{fill}"/>'


def E(cx, cy, rx, ry, w=6, fill='none', rot=0):
    return (f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}" stroke-width="{w}" '
            f'fill="{fill}" transform="rotate({rot} {cx} {cy})"/>')


def T(x, y, txt, size=40, rot=0, anchor='middle'):
    return (f'<text x="{x}" y="{y}" font-size="{size}" text-anchor="{anchor}" '
            f'transform="rotate({rot} {x} {y})" stroke="none" fill="#000" '
            f'font-family="Comic Neue, Comic Sans MS, Patrick Hand, sans-serif" '
            f'font-weight="700">{txt}</text>')


def bochecha(cx, cy, r=14, seed=1):
    """Bochecha às pintinhas, como nas personagens do Pica."""
    rnd = random.Random(seed)
    s = C(cx, cy, r, 3)
    for _ in range(9):
        a = rnd.uniform(0, 2 * math.pi)
        d = rnd.uniform(0, r * 0.7)
        s += C(round(cx + d * math.cos(a), 1), round(cy + d * math.sin(a), 1), 1.8, 0, '#000')
    return s


def raios(cx, cy, r1, r2, n, w=5, desvio=0):
    s = ''
    for i in range(n):
        a = 2 * math.pi * i / n + desvio
        s += P(f'M{cx + r1 * math.cos(a):.0f} {cy + r1 * math.sin(a):.0f} '
               f'L{cx + r2 * math.cos(a):.0f} {cy + r2 * math.sin(a):.0f}', w)
    return s


def tracejado(pontos, w=4):
    return ''.join(P(f'M{x1} {y1} L{x2} {y2}', w) for x1, y1, x2, y2 in pontos)


