def roda_raios(cx, cy, r, n=10, w=6):
    """Roda de bicicleta: aro, cubo e raios."""
    s = C(cx, cy, r, w) + C(cx, cy, 6, 0, '#000')
    for i in range(n):
        a = math.pi * i / n
        s += P(f'M{cx + r * math.cos(a):.0f} {cy + r * math.sin(a):.0f} '
               f'L{cx - r * math.cos(a):.0f} {cy - r * math.sin(a):.0f}', 2)
    return s


